    <h3>1. Ketentuan Umum</h3>
    <ol>
        <li>Peminjaman ruang dilakukan melalui sistem ini dan baru sah setelah <strong>disetujui admin</strong>.</li>
        <li>Pemohon wajib mengisi data dengan benar dan dapat dipertanggungjawabkan.</li>
        <li>Ruangan digunakan sesuai tujuan dan waktu yang diajukan.</li>
    </ol>
    <h3>2. Penggunaan Ruangan</h3>
    <ol>
        <li>Peminjam wajib menjaga kebersihan, ketertiban, dan keamanan ruangan serta fasilitasnya.</li>
        <li>Kerusakan atau kehilangan fasilitas selama masa peminjaman menjadi tanggung jawab peminjam.</li>
        <li>Ruangan dikembalikan dalam kondisi semula tepat pada waktu selesai peminjaman.</li>
        <li>Dilarang memindahtangankan hak peminjaman kepada pihak lain.</li>
    </ol>
    <h3>3. Pembatalan</h3>
    <ol>
        <li>Pembatalan dilakukan melalui sistem sebelum waktu peminjaman dimulai.</li>
        <li>Pihak universitas berhak membatalkan peminjaman untuk kepentingan institusi, dengan pemberitahuan kepada peminjam.</li>
    </ol>
    <h3>4. Data Pribadi</h3>
    <ol>
        <li>Data pribadi (termasuk KTP bagi pengguna eksternal) hanya digunakan untuk verifikasi peminjaman dan disimpan secara terbatas.</li>
    </ol>
